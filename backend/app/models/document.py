from datetime import UTC, datetime
from enum import StrEnum
from typing import Any
from uuid import UUID, uuid4

from pgvector.sqlalchemy import Vector
from sqlalchemy import JSON, Column, Text
from sqlmodel import Field, SQLModel


class DocumentStatus(StrEnum):
    """
    Lifecycle status of an ingested corporate document.
    """

    PENDING = "pending"
    PROCESSING = "processing"
    READY = "ready"
    FAILED = "failed"


class Document(SQLModel, table=True):
    """
    Metadata representation of an uploaded corporate document (contract, invoice, report).
    Stores cryptographic hashes for tamper-proof audit trails.
    """

    __tablename__ = "documents"

    id: UUID = Field(
        default_factory=uuid4,
        primary_key=True,
        index=True,
        nullable=False,
    )
    tenant_id: UUID = Field(
        foreign_key="tenants.id",
        index=True,
        nullable=False,
    )
    uploaded_by: UUID = Field(
        foreign_key="users.id",
        index=True,
        nullable=False,
    )
    filename: str = Field(max_length=255, nullable=False)
    file_path: str = Field(max_length=1024, nullable=False)
    file_size_bytes: int = Field(nullable=False)
    mime_type: str = Field(default="application/pdf", max_length=100, nullable=False)
    sha256_hash: str = Field(
        index=True,
        max_length=64,
        nullable=False,
        description="Cryptographic SHA-256 hash of document bytes for audit tamper detection",
    )
    status: DocumentStatus = Field(default=DocumentStatus.PENDING, nullable=False)
    total_pages: int | None = Field(default=None, nullable=True)
    error_message: str | None = Field(default=None, max_length=1000, nullable=True)
    created_at: datetime = Field(
        default_factory=lambda: datetime.now(UTC),
        nullable=False,
    )
    updated_at: datetime = Field(
        default_factory=lambda: datetime.now(UTC),
        nullable=False,
    )


class DocumentChunk(SQLModel, table=True):
    """
    Atomic text segment extracted from a document for Hybrid RAG.
    Stores exact page attribution, bounding-box coordinates, and 1024-dim dense vectors.
    """

    __tablename__ = "document_chunks"

    id: UUID = Field(
        default_factory=uuid4,
        primary_key=True,
        index=True,
        nullable=False,
    )
    document_id: UUID = Field(
        foreign_key="documents.id",
        index=True,
        nullable=False,
    )
    tenant_id: UUID = Field(
        foreign_key="tenants.id",
        index=True,
        nullable=False,
    )
    chunk_index: int = Field(nullable=False)
    page_number: int = Field(
        index=True,
        nullable=False,
        description="1-indexed physical page number in the original PDF",
    )
    # Bounding box coordinates formatted as [x1, y1, x2, y2] normalized (0.0 to 1.0)
    bounding_box: list[float] | None = Field(
        default=None,
        sa_column=Column(JSON, nullable=True),
        description="Normalized coordinates [x1, y1, x2, y2] for frontend PDF highlight overlay",
    )
    content: str = Field(
        sa_column=Column(Text, nullable=False),
        description="Sanitized and PII-redacted text content used for LLM inference",
    )
    raw_content_masked: bool = Field(
        default=False,
        nullable=False,
        description="True if personal identifiable information (PII) was scrubbed by Presidio",
    )
    token_count: int = Field(default=0, nullable=False)
    # Dense vector embedding generated by BAAI/bge-m3 (1024 dimensions)
    embedding: Any | None = Field(
        default=None,
        sa_column=Column(Vector(1024), nullable=True),
        description="1024-dimensional dense semantic embedding vector for pgvector cosine search",
    )
    created_at: datetime = Field(
        default_factory=lambda: datetime.now(UTC),
        nullable=False,
    )
